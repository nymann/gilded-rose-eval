package com.gildedrose;

public class OracleStone {
    public String name;
    public int day;
    public int quality;
    public boolean sealed;

    public OracleStone(int day, int quality, boolean sealed) {
        this.name = "Oracle Stone";
        this.day = day;
        this.quality = quality;
        this.sealed = sealed;
    }
}
